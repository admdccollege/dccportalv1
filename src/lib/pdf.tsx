import "server-only";
import { Document, Page, StyleSheet, Text, View, renderToBuffer } from "@react-pdf/renderer";

const s = StyleSheet.create({
  page: { padding: 36, fontSize: 10, fontFamily: "Helvetica", color: "#17202b" },
  head: { borderBottomWidth: 2, borderBottomColor: "#16324f", paddingBottom: 8, marginBottom: 14, textAlign: "center" },
  college: { fontSize: 18, fontFamily: "Helvetica-Bold", color: "#16324f" },
  title: { fontSize: 12, marginTop: 4, fontFamily: "Helvetica-Bold" },
  row: { flexDirection: "row", marginBottom: 3 },
  key: { width: 110, color: "#55606e" },
  th: { flexDirection: "row", backgroundColor: "#16324f", color: "#fff", padding: 5, marginTop: 12, fontFamily: "Helvetica-Bold" },
  td: { flexDirection: "row", padding: 5, borderBottomWidth: 0.5, borderBottomColor: "#d5dae1" },
  foot: { position: "absolute", bottom: 30, left: 36, right: 36, fontSize: 8, color: "#55606e", borderTopWidth: 0.5, borderTopColor: "#d5dae1", paddingTop: 6 },
  total: { marginTop: 12, fontFamily: "Helvetica-Bold", fontSize: 11 },
});

function Header({ title }: { title: string }) {
  return <View style={s.head}><Text style={s.college}>Damdei Christian College</Text><Text style={s.title}>{title}</Text></View>;
}
function Facts({ items }: { items: [string, string | number | null | undefined][] }) {
  return <View>{items.filter(([, v]) => v !== null && v !== undefined && v !== "").map(([k, v]) => (
    <View key={k} style={s.row}><Text style={s.key}>{k}</Text><Text>{String(v)}</Text></View>
  ))}</View>;
}

export type CourseResult = { code: string; title: string; credits: number; percent: number; letter: string | null; grade_point: number | null };
export type MarkSheet = {
  studentName: string; enrollmentNo: string; tier: string; term: string; courses: CourseResult[];
  percentage: number | null; division: string | null; sgpa: number | null; cgpa: number | null;
  creditsEarned: number | null; creditsRegistered: number | null; hash: string; verifyUrl: string; publishedAt: string | null;
};

export function renderMarkSheet(m: MarkSheet) {
  const hs = m.tier === "higher_secondary";
  const col = hs ? ["60%", "20%", "20%"] : ["16%", "42%", "12%", "12%", "9%", "9%"];
  return renderToBuffer(
    <Document title={`Mark Sheet ${m.enrollmentNo}`} author="Damdei Christian College">
      <Page size="A4" style={s.page}>
        <Header title={hs ? "Report Card" : "Mark Sheet"} />
        <Facts items={[["Student", m.studentName], ["Enrollment No", m.enrollmentNo], ["Term", m.term]]} />
        <View style={s.th}>{(hs ? ["Subject", "Code", "Percent"] : ["Code", "Course", "Credits", "Percent", "Grade", "GP"]).map((h, i) => <Text key={h} style={{ width: col[i] }}>{h}</Text>)}</View>
        {m.courses.map((c) => (
          <View key={c.code} style={s.td} wrap={false}>
            {(hs ? [c.title, c.code, `${c.percent}%`] : [c.code, c.title, c.credits, `${c.percent}%`, c.letter ?? "-", c.grade_point ?? "-"]).map((v, i) => <Text key={i} style={{ width: col[i] }}>{String(v)}</Text>)}
          </View>
        ))}
        <Text style={s.total}>{hs ? `Overall: ${m.percentage}%   ${m.division ?? ""}` : `SGPA: ${m.sgpa ?? "-"}   CGPA: ${m.cgpa ?? "-"}   Credits earned: ${m.creditsEarned ?? 0} of ${m.creditsRegistered ?? 0}`}</Text>
        <View style={s.foot} fixed>
          <Text>Verify at {m.verifyUrl}</Text>
          <Text>Verification hash: {m.hash}</Text>
          <Text>Generated by the DCC Portal. This does not replace a certificate issued by the council or university.</Text>
        </View>
      </Page>
    </Document>,
  );
}

export type Receipt = {
  receiptNo: string; studentName: string; enrollmentNo: string; amount: number; mode: string; reference: string | null;
  paidOn: string; code: string; verifyUrl: string; voided: boolean;
};
const inr = (n: number) => `Rs. ${Number(n).toLocaleString("en-IN", { minimumFractionDigits: 2 })}`;

export function renderReceipt(r: Receipt) {
  return renderToBuffer(
    <Document title={`Receipt ${r.receiptNo}`} author="Damdei Christian College">
      <Page size="A5" orientation="landscape" style={s.page}>
        <Header title={r.voided ? "Fee Receipt (VOID)" : "Fee Receipt"} />
        <Facts items={[["Receipt No", r.receiptNo], ["Date", r.paidOn], ["Student", r.studentName], ["Enrollment No", r.enrollmentNo],
          ["Amount", inr(r.amount)], ["Mode", r.mode.replace("_", " ").toUpperCase()], ["Reference", r.reference]]} />
        <View style={s.foot} fixed><Text>Verification code: {r.code}. Verify at {r.verifyUrl}</Text></View>
      </Page>
    </Document>,
  );
}
